def run(s: Suite) -> str:
    print(f"  running {s.key} ...", file=sys.stderr, flush=True)
    p = subprocess.run(s.cmd, cwd=s.cwd, capture_output=True, text=True)
    if p.returncode != 0:
        sys.stderr.write(p.stdout[-4000:] + p.stderr[-4000:])
        raise SystemExit(f"{s.key}: `{' '.join(s.cmd)}` exited {p.returncode}")
    out = []
    for line in p.stdout.splitlines():
        drop = False
        for pat, rep in SCRUB_COMMON + s.scrub:
            if re.search(pat, line):
                if rep is None:
                    drop = True
                    break
                line = re.sub(pat, rep, line)
        if not drop:
            out.append(line.rstrip())
    while out and not out[-1]:
        out.pop()
    return "\n".join(out)


def command_text(s: Suite) -> str:
    cmd = ["cargo" if c == cargo() else ("python3" if c == PY else c) for c in s.cmd]
    where = "cd rust && " if s.cwd.endswith(os.sep + "rust") else ""
    return where + " ".join(cmd)


def section(s: Suite, body: str) -> str:
    tier = ("checked by CI on every push" if s.tier == "ci"
            else "slow: regenerated by hand with `--slow`, not checked by CI")
    return (f"<!-- results:begin {s.key} -->\n"
            f"## {s.title}\n\n"
            f"`{command_text(s)}` — {tier}\n\n"
            f"{s.note}\n\n"
            f"```text\n{body}\n```\n"
            f"<!-- results:end {s.key} -->")


HEADER = """# Results

Generated by `tools/results.py` from the commands named in each section.
**Do not edit by hand**: the next regeneration overwrites it, and CI fails
if a CI-tier section no longer matches what its command prints.

**Every number in this file is SYNTHETIC.** No board has ever run this
firmware (`docs/CAPABILITY_LIMITS.md`). These tables say the DSP is
internally consistent and behaves as designed on a simulator written by
the same project; they say nothing about real rooms, radios or bodies.

Two tiers. *CI-checked* sections are regenerated on every push and must
match to one unit in the last printed place. *Slow* sections are
regenerated by hand; `git log -- docs/RESULTS.md` dates them. Prose that
quotes a figure from a CI-checked section is checked too: the quotes are
registered in `tools/results.py` and a mismatch fails the build.
"""


def parse(text: str) -> dict[str, str]:
    found = {}
    for m in re.finditer(r"<!-- results:begin (\S+) -->\n(.*?)\n<!-- results:end \1 -->", text, re.S):
        found[m.group(1)] = m.group(0)
    return found


def render(sections: dict[str, str]) -> str:
    order = [s.key for s in suites()]
    parts = [HEADER] + [sections[k] for k in order if k in sections]
    return "\n\n".join(parts) + "\n"


NUM = re.compile(r"-?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?")


def decimals(token: str) -> int:
    if "e" in token.lower():
        return -1  # compare by significant figures below
    return len(token.split(".")[1]) if "." in token else 0


TOLERATED: list[str] = []


def same_number(a: str, b: str) -> bool:
    if a == b:
        return True
    try:
        x, y = float(a), float(b)
    except ValueError:
        return False
    d = max(decimals(a), decimals(b))
    if d == 0:
        return False  # integers are counts; they match exactly or not at all
    if d < 0:
        ok = abs(x - y) <= 1e-12 * max(abs(x), abs(y))
    else:
        ok = abs(x - y) <= 10 ** (-d) * 1.000001
    if ok:
        TOLERATED.append(f"{a} -> {b}")
    return ok


def compare_text(key: str, old: str, new: str) -> list[str]:
    problems = []
    a, b = old.splitlines(), new.splitlines()
    if len(a) != len(b):
        return [f"{key}: {len(a)} lines committed, {len(b)} generated"]
    for i, (la, lb) in enumerate(zip(a, b)):
        if la == lb:
            continue
        ta, tb = NUM.split(la), NUM.split(lb)
        na, nb = NUM.findall(la), NUM.findall(lb)
        if ta != tb or len(na) != len(nb) or not all(same_number(x, y) for x, y in zip(na, nb)):
            problems.append(f"{key}, line {i + 1}:\n    committed: {la}\n    generated: {lb}")
    return problems


def check_quotes(outputs: dict[str, str]) -> list[str]:
    problems = []
    for q in QUOTES:
        if q.suite not in outputs:
            continue
        with open(os.path.join(ROOT, q.file)) as fh:
            doc = fh.read()
        m = re.search(q.doc, doc)
        if not m:
            problems.append(f"{q.file}: the quote matching /{q.doc}/ is gone; "
                            f"update the registered pattern in tools/results.py")
            continue
        claimed = list(m.groups())
        actual = []
        for pat in q.out:
            om = re.search(pat, outputs[q.suite], re.M)
            if not om:
                problems.append(f"{q.suite} output no longer matches /{pat}/")
                break
            actual.extend(om.groups())
        else:
            if len(claimed) != len(actual):
                problems.append(f"{q.file}: {len(claimed)} numbers quoted, {len(actual)} extracted")
                continue
            for c, v in zip(claimed, actual):
                # A quote may round; it may not differ. Round the table's
                # value to the precision the prose printed, then require
                # equality.
                rounded = float(f"{float(v):.{max(decimals(c), 0)}f}")
                if rounded != float(c):
                    line = doc[:m.start()].count("\n") + 1
                    problems.append(f"{q.file}:{line} quotes {c}; `{q.suite}` now gives {v}")
    return problems


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--slow", action="store_true", help="also regenerate the slow tier")
    ap.add_argument("--check", action="store_true", help="compare, write nothing")
    ap.add_argument("--only", action="append", default=[], metavar="KEY",
                    help="regenerate only this section (repeatable)")
    args = ap.parse_args()

    tier = {"ci"} if args.check or not args.slow else {"ci", "slow"}
    if args.only:
        known = {s.key for s in suites()}
        unknown = set(args.only) - known
        if unknown:
            raise SystemExit(f"unknown section(s) {sorted(unknown)}; known: {sorted(known)}")
        chosen = [s for s in suites() if s.key in args.only]
    else:
        chosen = [s for s in suites() if s.tier in tier]

    committed = {}
    if os.path.exists(RESULTS):
        with open(RESULTS) as fh:
            committed = parse(fh.read())

    outputs, fresh = {}, {}
    for s in chosen:
        outputs[s.key] = run(s)
        fresh[s.key] = section(s, outputs[s.key])

    if args.check:
        problems = []
        for s in chosen:
            if s.key not in committed:
                problems.append(f"{s.key}: missing from docs/RESULTS.md; run tools/results.py")
                continue
            problems += compare_text(s.key, committed[s.key], fresh[s.key])
        problems += check_quotes(outputs)
        if problems:
            print(f"\n{len(problems)} disagreement(s):\n", file=sys.stderr)
            for p in problems:
                print(f"  {p}", file=sys.stderr)
            print("\nIf the code changed on purpose, run `python3 tools/results.py` and "
                  "update any prose it names. If it did not, something moved that "
                  "should not have.", file=sys.stderr)
            return 1
        if TOLERATED:
            print(f"{len(TOLERATED)} rounded value(s) differ by one unit in the last "
                  f"printed place, within tolerance: {', '.join(TOLERATED[:10])}")
        print(f"results: {len(chosen)} sections and {len(QUOTES)} quotes agree")
        return 0

    merged = dict(committed)
    merged.update(fresh)
    with open(RESULTS, "w") as fh:
        fh.write(render(merged))
    quote_problems = check_quotes(outputs)
    print(f"wrote {os.path.relpath(RESULTS, ROOT)} ({len(fresh)} sections regenerated)")
    if quote_problems:
        print("\nprose now disagrees with the tables:", file=sys.stderr)
        for p in quote_problems:
            print(f"  {p}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
