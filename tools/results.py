def cargo() -> str:
    found = shutil.which("cargo")
    if found:
        return found
    home = os.path.expanduser("~/.cargo/bin/cargo")
    if os.path.exists(home):
        return home
    raise SystemExit("cargo not found on PATH or in ~/.cargo/bin")


