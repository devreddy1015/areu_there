#!/usr/bin/env python3
"""Regenerate docs/RESULTS.md, and check that prose quotes it correctly.

WHY THIS EXISTS
---------------
Every stale number the review of PR #5 found had the same history: a
figure typed into a document from memory of a result, and then the code
moved and the document did not. Proofreading fixes the instances. This
fixes the mechanism: the tables are produced by the commands that compute
them, and the handful of figures that prose quotes are checked against
those tables on every push.

    python3 tools/results.py            regenerate the CI-tier sections
    python3 tools/results.py --slow     ... and the slow ones too (minutes)
    python3 tools/results.py --only K   regenerate just section K (any tier)
    python3 tools/results.py --check    regenerate the CI tier in memory,
                                        compare with the committed file and
                                        with every registered quote; exit 1
                                        on any disagreement. Writes nothing.

TWO TIERS
---------
CI-checked sections run in well under a minute on one core and are
regenerated on every push. Slow sections (the full Fresnel sweep, the
held-out S3 detector evaluation) take minutes to the better part of an
hour on a CI runner; they are regenerated by hand with --slow and are not
checked, so the commit that last touched a slow section is its date.
`saans-cli eval --quick` is deliberately NOT used to make the detector
table fast: its seeds are 0-1, which are the threshold-tuning seeds, and a
table computed on the data the thresholds were fitted to is not a result.

WHAT VARIES BETWEEN RUNS, AND IS SCRUBBED
-----------------------------------------
Measured before this was written: every suite here was run twice on one
machine, and the nulls suite at 1, 4 and 20 workers. The only lines that
changed were wall-clock times ("ran in 20s", "in 154 s"), progress lines
(which go to stderr and are not captured), and the printed worker count.
Every computed value was identical. SCRUB removes exactly those.

HOW NUMBERS ARE COMPARED
------------------------
Text must match exactly, and so must every integer: a count such as
51/64 is not a rounded value, and nothing about floating point can move
it except a reading that lands exactly on a classification threshold,
which is a behaviour change worth seeing. (The first version of this
check let integers through at +/-1 too; a hand edit of 51/64 to 52/64
passed it. Found by trying exactly that.)

A number with a decimal point is a rounded float, and may differ by one
unit in its last printed place. Two machines whose libm differ in the
sixteenth significant figure -- what failed the golden-drift job on its
first push -- can land either side of a rounding boundary. Any such
difference is printed, never passed silently. The full-precision check
that the DSP has not moved is spec/golden/check_drift.py, at 1e-11.
"""

